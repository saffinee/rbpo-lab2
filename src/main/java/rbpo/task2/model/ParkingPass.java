package rbpo.task2.model;

import java.time.LocalDateTime;

public class ParkingPass extends BaseEntity {
    private Long vehicleId;
    private Long zoneId;
    private LocalDateTime validFrom; //начало действия, ставит сервер
    private LocalDateTime validTo; //конец действия
    private String status; //например ACTIVE или CANCELLED

    public Long getVehicleId() {
        return vehicleId;
    }

    public void setVehicleId(Long vehicleId) {
        this.vehicleId = vehicleId;
    }

    public Long getZoneId() {
        return zoneId;
    }

    public void setZoneId(Long zoneId) {
        this.zoneId = zoneId;
    }

    public LocalDateTime getValidFrom() {
        return validFrom;
    }

    public void setValidFrom(LocalDateTime validFrom) {
        this.validFrom = validFrom;
    }

    public LocalDateTime getValidTo() {
        return validTo;
    }

    public void setValidTo(LocalDateTime validTo) {
        this.validTo = validTo;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
}
